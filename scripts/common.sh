set -euo pipefail

# ==============================================================================
# Diretório raiz do projeto
# ==============================================================================

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

# ==============================================================================
# Docker Compose
# ==============================================================================

COMPOSE_ARGS=(

    # --------------------------------------------------------------------------
    # Environment
    # --------------------------------------------------------------------------

    --env-file "${ROOT_DIR}/.env"

    # --------------------------------------------------------------------------
    # Main Compose
    # --------------------------------------------------------------------------

    -f "${ROOT_DIR}/compose/main-compose.yml"

    # --------------------------------------------------------------------------
    # Infrastructure
    # --------------------------------------------------------------------------

    -f "${ROOT_DIR}/compose/01-gluetun.yml"
    -f "${ROOT_DIR}/compose/02-qbittorrent.yml"
    -f "${ROOT_DIR}/compose/03-flaresolverr.yml"

    # --------------------------------------------------------------------------
    # Servarr
    # --------------------------------------------------------------------------

    -f "${ROOT_DIR}/compose/04-prowlarr.yml"
    -f "${ROOT_DIR}/compose/05-sonarr.yml"
    -f "${ROOT_DIR}/compose/06-radarr.yml"
    -f "${ROOT_DIR}/compose/07-lidarr.yml"
    -f "${ROOT_DIR}/compose/08-bazarr.yml"

    # --------------------------------------------------------------------------
    # Streaming
    # --------------------------------------------------------------------------

    -f "${ROOT_DIR}/compose/09-jellyfin.yml"
    -f "${ROOT_DIR}/compose/10-jellyseerr.yml"

    # --------------------------------------------------------------------------
    # Automation
    # --------------------------------------------------------------------------

    -f "${ROOT_DIR}/compose/11-recyclarr.yml"
    -f "${ROOT_DIR}/compose/12-unpackerr.yml"

)

# ==============================================================================
# Helper Functions
# ==============================================================================

docker_compose() {
    docker compose "${COMPOSE_ARGS[@]}" "$@"
}
)